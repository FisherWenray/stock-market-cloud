/**
 * Ensures every stock has a meaningful secondary industry (subsector).
 */
export function enrichStockSubsector(stock: Stock): Stock {
  if (stock.subsector) return stock;

  if (KNOWN_STOCK_SUBSECTOR[stock.name]) {
    return { ...stock, subsector: KNOWN_STOCK_SUBSECTOR[stock.name] };
  }

  const subsectors = SECTOR_SUBSECTORS[stock.sector];
  if (!subsectors || subsectors.length === 0) {
    return { ...stock, subsector: stock.sector };
  }

  // Deterministically assign based on stock code/name hash
  let hash = 0;
  const key = stock.symbol + stock.name;
  for (let i = 0; i < key.length; i++) {
    hash = key.charCodeAt(i) + ((hash << 5) - hash);
  }
  const index = Math.abs(hash) % subsectors.length;
  return { ...stock, subsector: subsectors[index] };
}

export function enrichStocksWithTaxonomy(stocks: Stock[]): Stock[] {
  return stocks.map(enrichStockSubsector);
}
